#!/usr/bin/env python3
"""Build web/shell.html (the Web export's custom HTML shell) from web/shell.src.html.

The launch page must work offline (PWA): the service worker only caches the files Godot
exports, so the page's fonts and stills are inlined as data URIs instead of separate files.
  {{font:Name}} -> web/launch/Name.woff2     {{img:name}} -> web/launch/name.webp
Run by tools/export_web.sh before every export; commit the generated web/shell.html too.
"""
import base64
import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
SRC = ROOT / "web" / "shell.src.html"
OUT = ROOT / "web" / "shell.html"
ASSETS = ROOT / "web" / "launch"
KINDS = {"font": ("woff2", "font/woff2"), "img": ("webp", "image/webp")}


def data_uri(match: re.Match) -> str:
    kind, name = match.group(1), match.group(2)
    ext, mime = KINDS[kind]
    path = ASSETS / f"{name}.{ext}"
    if not path.is_file():
        sys.exit(f"build_web_shell: missing {path}")
    return f"data:{mime};base64,{base64.b64encode(path.read_bytes()).decode('ascii')}"


def main() -> None:
    html = SRC.read_text(encoding="utf-8")
    html = re.sub(r"\{\{(font|img):([A-Za-z0-9_]+)\}\}", data_uri, html)
    banner = "<!-- Generated by tools/build_web_shell.py from web/shell.src.html. Do not edit. -->\n"
    OUT.write_text(html.replace("<!DOCTYPE html>\n", "<!DOCTYPE html>\n" + banner, 1), encoding="utf-8")
    print(f"build_web_shell: wrote {OUT.relative_to(ROOT)} ({OUT.stat().st_size // 1024} KiB)")


if __name__ == "__main__":
    main()
